"""Compare the two reference tokenizers and emit the Swift test fixture.

Only cases where both implementations agree become strict expectations.
Disagreements are recorded explicitly with open_clip as the resolved answer,
because it trained these weights — but they are marked so that a reader knows
the Swift implementation is matching open_clip by choice, not by accident.
"""
import json
import sys

with open(sys.argv[1]) as handle:
    oc = json.load(handle)
with open(sys.argv[2]) as handle:
    hf = json.load(handle)
out_path = sys.argv[3]

hf_by_text = {c["text"]: c["ids"] for c in hf["cases"]}

cases = []
disagreements = []
for case in oc["cases"]:
    text = case["text"]
    oc_ids = case["ids"]
    hf_ids = hf_by_text.get(text)
    agree = oc_ids == hf_ids
    cases.append(
        {
            "text": text,
            "expected": oc_ids,
            "bothImplementationsAgree": agree,
        }
    )
    if not agree:
        disagreements.append((text, oc_ids, hf_ids))

fixture = {
    "_comment": (
        "Generated by tools/compare_refs.py. Do not hand-edit. "
        "'expected' is open_clip.SimpleTokenizer output, which is authoritative "
        "for the LAION OpenCLIP weights. 'bothImplementationsAgree' records "
        "whether Hugging Face's CLIPTokenizerFast produced the same IDs."
    ),
    "sotTokenID": oc["sot_token_id"],
    "eotTokenID": oc["eot_token_id"],
    "vocabSize": oc["vocab_size"],
    "contextLength": oc["context_length"],
    "cases": cases,
}
with open(out_path, "w") as handle:
    json.dump(fixture, handle, indent=1, ensure_ascii=False)
    handle.write("\n")

print(f"cases: {len(cases)}  agree: {sum(c['bothImplementationsAgree'] for c in cases)}")
for text, a, b in disagreements:
    print(f"\n  DISAGREE {text!r}")
    print(f"    open_clip ({len(a)}): {a[:20]}")
    print(f"    hf        ({len(b)}): {b[:20]}")
